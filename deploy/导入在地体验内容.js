const PAGES = [
  { pageCode: 'trip_itineraries', title: '推荐行程', content: TRIP_ITINERARIES, sortOrder: 9 },
  { pageCode: 'solar_terms', title: '二十四节气 · 东方村落文明', content: SOLAR_TERMS, sortOrder: 10 },
];

async function main() {
  const dryRun = process.argv.includes('--dry-run');
  const prisma = new PrismaClient();
  try {
    for (const page of PAGES) {
      const existing = await prisma.contentPage.findUnique({ where: { pageCode: page.pageCode } });
      const data = { title: page.title, content: JSON.stringify(page.content), type: 'cms', status: 1, sortOrder: page.sortOrder };
      const size = page.content.itineraries ? `${page.content.itineraries.length} 条行程` : `${page.content.terms.length} 个节气/节日`;
      console.log(`${existing ? '更新' : '新建'} ${page.pageCode} ${page.title}（${size}）`);
      if (dryRun) continue;
      await prisma.contentPage.upsert({ where: { pageCode: page.pageCode }, update: data, create: { pageCode: page.pageCode, ...data } });
    }
    console.log(`${dryRun ? '[演练，未写入] ' : ''}完成`);
  } finally {
    await prisma.$disconnect();
  }
}

main().catch((err) => {
  console.error(err);
  process.exit(1);
});
